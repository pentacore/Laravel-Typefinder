    /**
     * Render a category barrel: one re-export line per file.
     *
     * @param  list<string>|array<string, list<string>>  $typeNames  the file names, each exporting the type it
     *                                                               is named after; or the exported type names by file name
     */
    public function renderBarrelIndex(array $typeNames): string
    {
        $exportsByFile = array_is_list($typeNames)
            ? array_combine($typeNames, array_map(fn (string $name): array => [$name], $typeNames))
            : $typeNames;

        ksort($exportsByFile, SORT_STRING);

        $lines = [];
        foreach ($exportsByFile as $file => $names) {
            $lines[] = sprintf("export type { %s } from './%s';", implode(', ', $names), $file);
        }

        return self::FILE_HEADER."\n".implode("\n", $lines)."\n";
    }

    /**
     * The types a rendered file exports: the one the file is named after
     * first, then the others (write shapes, a query type, extracted nested
     * types) in file order.
     *
     * @return list<string>
     */
    public static function exportedTypeNames(string $content, string $own): array
    {
        preg_match_all('/^export type ([A-Za-z_$][\w$]*)/m', $content, $matches);

        return array_values(array_unique([$own, ...$matches[1]]));
    }

    /**
     * Render the top-level barrel index.d.ts file.
     *
     * @param  list<string>  $categories
     */
    public function renderTopLevelBarrel(array $categories): string
    {
        $lines = array_map(
            fn (string $cat): string => sprintf("export type * from './%s';", $cat),
            $categories
        );

        return self::FILE_HEADER."\n".implode("\n", $lines)."\n";
    }

    /**
     * Resolve a type value to a TypeScript type string.
     *
     * @param  list<array>  $allEnums
     * @param  list<string>  $imports  (passed by reference)
     */
    protected function resolveTypeString(
        mixed $type,
        bool $nullable,
        array $allEnums,
        array &$imports,
        string $fromDir,
        ?string $selfFqcn = null,
        array $allModels = [],
    ): string {
        if (is_string($type)) {
            // Overrides (#[TypefinderOverrides]) may carry class-strings.
            return $this->resolveClassString($type, $fromDir, $allModels, $allEnums, [], $imports, $selfFqcn);
        }

        if (is_array($type)) {
            if (isset($type['enum'])) {
                $enumName = $this->resolveEnumName($type['enum'], $allEnums);
                $imports[] = sprintf("import type { %s } from '../enums';", $enumName);

                return $enumName;
            }

            if (isset($type['enumCollection'])) {
                $enumName = $this->resolveEnumName($type['enumCollection'], $allEnums);
                $imports[] = sprintf("import type { %s } from '../enums';", $enumName);

                return $enumName.'[]';
            }

            if (array_key_exists('arrayOf', $type)) {
                $itemType = $this->resolveTypeString($type['arrayOf'], false, $allEnums, $imports, $fromDir, $selfFqcn, $allModels);

                return (str_contains($itemType, ' | ') ? '('.$itemType.')' : $itemType).'[]';
            }

            if (isset($type['in'])) {
                $values = array_map(fn (string $v): string => sprintf("'%s'", $v), $type['in']);

                return implode(' | ', $values);
            }

            if (isset($type['anyOf'])) {
                return implode(' | ', array_unique($type['anyOf']));
            }
        }

        return 'unknown';
    }

    /**
     * Render a relationship as a type field line.
     */
    protected function renderRelationshipField(array $rel, array $allModels, array &$imports): ?string
    {
        $name = $rel['name'];

        switch ($rel['type']) {
            case 'one':
            case 'belongsTo':
                $relatedName = $this->resolveModelName($rel['related'], $allModels);
                $imports[] = sprintf("import type { %s } from './%s';", $relatedName, $relatedName);

                return sprintf('  %s?: %s | null;', $name, $relatedName);

            case 'many':
                $relatedName = $this->resolveModelName($rel['related'], $allModels);
                $imports[] = sprintf("import type { %s } from './%s';", $relatedName, $relatedName);

                return sprintf('  %s?: %s[];', $name, $relatedName);

            case 'manyWithPivot':
                $relatedName = $this->resolveModelName($rel['related'], $allModels);
                $imports[] = sprintf("import type { %s } from './%s';", $relatedName, $relatedName);
                $pivotName = $this->generatePivotName($rel['pivot']['table'] ?? $name);
                $imports[] = sprintf("import type { %s } from './%s';", $pivotName, $pivotName);

                return sprintf('  %s?: (%s & { pivot: %s })[];', $name, $relatedName, $pivotName);

            case 'morphTo':
                return sprintf('  %s?: T | null;', $name);

            default:
                return null;
        }
    }

    /**
     * Render a request field. Nested objects and object arrays recurse, to
     * any depth: inline, or as a named type each when $extractNested is on.
     *
     * @param  string  $typeName  the type the field belongs to; prefixes the names of extracted nested types
     * @param  array<string, string>  $extractedTypes  extracted nested types by name, in output order
     */
    protected function renderRequestField(
        array $field,
        string $typeName,
        array $allEnums,
        array &$imports,
        array &$lines,
        array &$extractedTypes,
        bool $extractNested,
        int $indent = 1,
    ): void {
        $prefix = str_repeat('  ', $indent);
        $key = self::propertyKey((string) $field['name']);
        $optional = $field['required'] ? '' : '?';
        $nullable = (bool) $field['nullable'];

        $isObjectArray = $field['type'] === 'object-array';

        if ($field['type'] !== 'object' && ! $isObjectArray || ! isset($field['children'])) {
            $typeStr = $this->resolveTypeString($field['type'], $nullable, $allEnums, $imports, 'requests');
            $lines[] = sprintf('%s%s%s: %s;', $prefix, $key, $optional, self::appendNullable($typeStr, $nullable));

            return;
        }

        // `items.*.*.name` is an array of arrays of objects.
        $arraySuffix = $isObjectArray ? str_repeat('[]', max(1, (int) ($field['arrayDepth'] ?? 1))) : '';

        if ($extractNested) {
            $nestedName = $this->nestedTypeName($typeName, (string) $field['name'], $extractedTypes);
            // Reserve the name and the position: a parent is listed before its own nested types.
            $extractedTypes[$nestedName] = '';

            $nestedLines = [];
            foreach ($field['children'] as $child) {
                $this->renderRequestField($child, $nestedName, $allEnums, $imports, $nestedLines, $extractedTypes, true);
            }

            $extractedTypes[$nestedName] = "export type {$nestedName} = {\n".implode("\n", $nestedLines)."\n};";
            $lines[] = sprintf('%s%s%s: %s;', $prefix, $key, $optional, self::appendNullable($nestedName.$arraySuffix, $nullable));

            return;
        }

        $lines[] = sprintf('%s%s%s: {', $prefix, $key, $optional);
        foreach ($field['children'] as $child) {
            $this->renderRequestField($child, $typeName, $allEnums, $imports, $lines, $extractedTypes, false, $indent + 1);
        }

        $lines[] = sprintf('%s}%s%s;', $prefix, $arraySuffix, $nullable ? ' | null' : '');
    }

    /**
     * Name for an extracted nested type: the owning type's name plus the
     * field name, made a valid identifier and unique within the file.
     *
     * @param  array<string, string>  $taken
     */
    protected function nestedTypeName(string $typeName, string $fieldName, array $taken): string
    {
        $suffix = self::isIdentifier($fieldName)
            ? ucfirst($fieldName)
            : implode('', array_map(ucfirst(...), preg_split('/[^A-Za-z0-9_$]+/', $fieldName, -1, PREG_SPLIT_NO_EMPTY) ?: []));

        $name = $typeName.($suffix === '' ? 'Field' : $suffix);
        $candidate = $name;

        for ($n = 2; isset($taken[$candidate]); $n++) {
            $candidate = $name.$n;
        }

        return $candidate;
    }

    protected function resolveEnumName(string $fqcn, array $allEnums): string
    {
        foreach ($allEnums as $allEnum) {
            if ($allEnum['fqcn'] === $fqcn) {
                return $allEnum['name'];
            }
        }

        $parts = explode('\\', $fqcn);

        return end($parts);
    }

    protected function resolveModelName(string $fqcn, array $allModels): string
    {
        foreach ($allModels as $allModel) {
            if ($allModel['fqcn'] === $fqcn) {
                return $allModel['name'];
            }
        }

        $parts = explode('\\', $fqcn);

        return end($parts);
    }

    /**
     * @return list<string>
     */
    protected function resolveModelNames(array $fqcns, array $allModels): array
    {
        return array_map(fn (string $fqcn): string => $this->resolveModelName($fqcn, $allModels), $fqcns);
    }

    protected function generatePivotName(string $tableName): string
    {
        return PivotResolver::typeName($tableName);
    }
}
