<?php

declare(strict_types=1);

namespace Pentacore\Typefinder\Renderers;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Http\Resources\Json\JsonResource;
use Pentacore\Typefinder\Renderers\Concerns\RendersBroadcasting;
use Pentacore\Typefinder\Renderers\Concerns\RendersModels;
use Pentacore\Typefinder\Renderers\Concerns\RendersResources;

class TypeScriptRenderer
{
    use RendersBroadcasting;
    use RendersModels;
    use RendersResources;

    public const string FILE_HEADER = <<<'TS'
        // ───────────────────────────────────────────────────────────────────────
        // This file is auto-generated by laravel-typefinder.
        // Do not edit it by hand — re-run `php artisan typefinder:generate`.
        // https://github.com/pentacore/laravel-typefinder
        // ───────────────────────────────────────────────────────────────────────

        TS;

    /**
     * Append ` | null` to a TS type string when the column/field is nullable,
     * unless `null` is already a top-level union member of the type. Prevents
     * `... | null | null` when an override or cast already wrote the union.
     *
     * Splits on `|` while respecting bracket depth so generics like
     * `Record<string, null>` aren't mistaken for a top-level null union.
     */
    public static function appendNullable(string $type, bool $nullable): string
    {
        if (! $nullable) {
            return $type;
        }

        if (self::unionContainsNull($type)) {
            return $type;
        }

        return $type.' | null';
    }

    private static function unionContainsNull(string $type): bool
    {
        $depth = 0;
        $current = '';
        $length = strlen($type);

        for ($i = 0; $i < $length; $i++) {
            $character = $type[$i];

            if (in_array($character, ['<', '{', '(', '['], true)) {
                $depth++;
                $current .= $character;

                continue;
            }

            if (in_array($character, ['>', '}', ')', ']'], true)) {
                $depth--;
                $current .= $character;

                continue;
            }

            if ($character === '|' && $depth === 0) {
                if (trim($current) === 'null') {
                    return true;
                }

                $current = '';

                continue;
            }

            $current .= $character;
        }

        return trim($current) === 'null';
    }

    /**
     * Render an enum to a file content string.
     *
     * When $emitValues is false (default), produces a `.d.ts`-style union
     * type alias. When true, produces a `.ts` file pairing an `as const`
     * object with a matching type derived from it — giving consumers both
     * a runtime value for iteration (`Object.values(PostStatus)`) and the
     * same union type for parameters. Callers must write the output to a
     * `.ts` file in that case; barrels should also be `.ts` so the runtime
     * export isn't stripped.
     */
    public function renderEnum(array $enum, bool $emitValues = false): string
    {
        $name = $enum['name'];
        $backingType = $enum['backingType'];

        if (! $emitValues) {
            $valueStrings = array_map(function (string|int $value) use ($backingType): string {
                if ($backingType === 'string') {
                    return sprintf("'%s'", $value);
                }

                return (string) $value;
            }, $enum['values']);

            $union = implode(' | ', $valueStrings);

            return self::FILE_HEADER."\nexport type {$name} = {$union};\n";
        }

        $cases = $enum['cases'] ?? [];
        $entries = array_map(function (array $case) use ($backingType): string {
            $value = $backingType === 'string'
                ? sprintf("'%s'", $case['value'])
                : (string) $case['value'];

            return sprintf('    %s: %s,', $case['name'], $value);
        }, $cases);

        $body = "export const {$name} = {\n".implode("\n", $entries)."\n} as const;\n\n";
        $body .= "export type {$name} = typeof {$name}[keyof typeof {$name}];\n";

        return self::FILE_HEADER."\n".$body;
    }

    /**
     * Render the consolidated pages.d.ts content.
     *
     * @param  list<array{component: string, props: array<string, string>, optional: list<string>}>  $pages
     * @param  list<array>  $allModels
     * @param  list<array>  $allEnums
     */
    public function renderPages(array $pages, array $allModels, array $allEnums, array $allResources = []): string
    {
        $imports = [];
        $entries = [];

        usort($pages, fn (array $a, array $b): int => strcmp((string) $a['component'], (string) $b['component']));

        foreach ($pages as $page) {
            $propLines = [];
            foreach ($page['props'] as $name => $type) {
                $resolved = $this->resolveClassString((string) $type, '', $allModels, $allEnums, $allResources, $imports);
                $optional = in_array($name, $page['optional'], true) ? '?' : '';
                $propLines[] = sprintf('%s%s: %s', $name, $optional, $resolved);
            }

            $entries[] = sprintf("  '%s': { ", $page['component']).implode('; ', $propLines).' };';
        }

        $imports = array_values(array_unique($imports));
        sort($imports);

        $output = self::FILE_HEADER."\n";
        if ($imports !== []) {
            $output .= implode("\n", $imports)."\n\n";
        }

        $output .= "export type PageProps = {\n";
        $output .= implode("\n", $entries)."\n";
        $output .= "};\n\n";

        return $output."export type PageName = keyof PageProps;\n";
    }

    /**
     * Replace class-strings in a type string with the generated type names and
     * record the import each one needs.
     *
     * Every namespaced class name in the string is checked, so unions, `[]`
     * suffixes and generics keep their exact text (`App\Models\User | null`
     * becomes `User | null`). Names that are not a model, enum or resource
     * are left as written.
     *
     * @param  string  $fromDir  Directory of the file being written, relative to
     *                           the output path: '' for root files (pages.d.ts,
     *                           broadcasting.d.ts), else 'models', 'resources'
     *                           or 'requests'.
     * @param  list<array>  $allModels
     * @param  list<array>  $allEnums
     * @param  list<array>  $allResources
     * @param  list<string>  $imports
     * @param  ?string  $selfFqcn  The class the file declares; never imported.
     */
    protected function resolveClassString(
        string $type,
        string $fromDir,
        array $allModels,
        array $allEnums,
        array $allResources,
        array &$imports,
        ?string $selfFqcn = null,
    ): string {
        if (! str_contains($type, '\\')) {
            return $type;
        }

        $prefix = $fromDir === '' ? './' : '../';

        return (string) preg_replace_callback(
            '/\\\\?[A-Za-z_][A-Za-z0-9_]*(?:\\\\[A-Za-z_][A-Za-z0-9_]*)+/',
            function (array $match) use ($fromDir, $prefix, $allModels, $allEnums, $allResources, &$imports, $selfFqcn): string {
                $class = ltrim($match[0], '\\');

                if (class_exists($class) && is_subclass_of($class, JsonResource::class)) {
                    $short = $this->resolveResourceName($class, $allResources);
                    $from = $fromDir === 'resources' ? './'.$short : $prefix.'resources';
                } elseif (class_exists($class) && is_subclass_of($class, Model::class)) {
                    $short = $this->resolveModelName($class, $allModels);
                    $from = $fromDir === 'models' ? './'.$short : $prefix.'models';
                } elseif (enum_exists($class)) {
                    $short = $this->resolveEnumName($class, $allEnums);
                    $from = $prefix.'enums';
                } else {
                    return $match[0];
                }

                if ($class !== $selfFqcn) {
                    $imports[] = sprintf("import type { %s } from '%s';", $short, $from);
                }

                return $short;
            },
            $type,
        );
    }

    /**
     * Render a request to a .d.ts file content string.
     *
     * @param  list<array>  $allEnums
     */
    public function renderRequest(array $request, array $allEnums, bool $extractNested = false): string
    {
        $imports = [];
        $extractedTypes = [];
        $lines = [];

        foreach ($request['fields'] as $field) {
            $this->renderRequestField($field, $request['name'], $allEnums, $imports, $lines, $extractedTypes, $extractNested);
        }

        $imports = array_values(array_unique($imports));
        sort($imports);

        $output = self::FILE_HEADER."\n";
        if ($imports !== []) {
            $output .= implode("\n", $imports)."\n\n";
        }

        foreach ($extractedTypes as $extractedType) {
            $output .= $extractedType."\n\n";
        }

        if ($lines === []) {
            return $output."export type {$request['name']} = Record<string, never>;\n";
        }

        $output .= "export type {$request['name']} = {\n";
        $output .= implode("\n", $lines)."\n";

        return $output."};\n";
    }

    /**
     * Render a pivot type to a .d.ts file content string.
     */
    public function renderPivot(array $pivot): string
    {
        $lines = [];
        $seen = [];

        foreach ($pivot['columns'] as $column) {
            if (isset($seen[$column['name']])) {
                continue;
            }

            $seen[$column['name']] = true;
            $nullable = (bool) ($column['nullable'] ?? false);
            $lines[] = sprintf('  %s: %s;', $column['name'], self::appendNullable($column['type'], $nullable));
        }

        // Laravel's withTimestamps() already lists the timestamp columns among
        // the pivot columns, so only add the ones that aren't there yet.
        if ($pivot['withTimestamps'] ?? false) {
            foreach (['created_at', 'updated_at'] as $timestamp) {
                if (! isset($seen[$timestamp])) {
                    $lines[] = sprintf('  %s: string | null;', $timestamp);
                }
            }
        }

        return self::FILE_HEADER."\nexport type {$pivot['name']} = {\n".implode("\n", $lines)."\n};\n";
    }

    /**
     * Render a barrel index.d.ts file.
     *
     * @param  list<string>  $typeNames
     */
    /**
     * Render a JSON resource (.d.ts) file content.
     *
     * @param  array{name: string, fqcn: string, shape: array}  $resource
     * @param  list<array>  $allModels
     * @param  list<array>  $allEnums
     * @param  list<array>  $allResources
     */
    public function renderHelpers(): string
    {
        return self::FILE_HEADER."\n".<<<'TS'
